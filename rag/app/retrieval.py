"""Load Saral's local retrieval index and perform exact cosine similarity search."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol

import numpy as np

from .embeddings import OpenRouterEmbeddingClient


class QueryEmbedder(Protocol):
    """Embedding operation needed by runtime query retrieval."""

    model: str

    async def embed_query(self, text: str) -> list[float]: ...

    async def aclose(self) -> None: ...


@dataclass(frozen=True)
class RetrievedChunk:
    """One source-grounded result from Saral's local article index."""

    id: str
    article_slug: str
    article_title: str
    article_url: str
    heading: str
    text: str
    score: float
    metadata_matched: bool = False

    def source(self) -> dict[str, str]:
        return {
            "title": self.article_title,
            "url": self.article_url,
            "heading": self.heading,
        }


@dataclass(frozen=True)
class ArticleReference:
    title: str
    slug: str
    url: str


@dataclass(frozen=True)
class ArticleCostReference:
    title: str
    slug: str
    url: str
    total_cost_usd: float | None
    cost_status: str | None
    models: tuple[str, ...]
    stages: tuple[dict[str, Any], ...]


class RetrievalIndex:
    """An immutable, in-memory index generated by :mod:`rag.scripts.ingest`."""

    def __init__(
        self,
        chunks: list[dict[str, Any]],
        embeddings: np.ndarray,
        *,
        model_name: str,
        embedder: QueryEmbedder | None = None,
    ) -> None:
        if not chunks:
            raise ValueError("The retrieval index contains no chunks.")
        if embeddings.ndim != 2 or embeddings.shape[0] != len(chunks):
            raise ValueError("embeddings.npy does not match the number of chunks in chunks.json.")
        if embeddings.shape[1] == 0:
            raise ValueError("embeddings.npy has no vector dimensions.")

        self._chunks = chunks
        self._embeddings = self._normalise(np.asarray(embeddings, dtype=np.float32))
        self.model_name = model_name
        self._embedder = embedder

    @classmethod
    def load(cls, data_dir: Path, *, embedder: QueryEmbedder | None = None) -> "RetrievalIndex":
        """Load and validate local artifacts without modifying them."""

        chunks_path = data_dir / "chunks.json"
        vectors_path = data_dir / "embeddings.npy"
        manifest_path = data_dir / "index-manifest.json"
        for path in (chunks_path, vectors_path, manifest_path):
            if not path.is_file():
                raise FileNotFoundError(
                    f"Missing retrieval artifact: {path}. Run 'python -m rag.scripts.ingest' first."
                )

        document = json.loads(chunks_path.read_text(encoding="utf-8"))
        if not isinstance(document, dict) or not isinstance(document.get("chunks"), list):
            raise ValueError("chunks.json must contain a top-level 'chunks' list.")
        chunks = document["chunks"]
        required_fields = {"id", "articleSlug", "articleTitle", "articleUrl", "heading", "text"}
        for number, chunk in enumerate(chunks, start=1):
            if not isinstance(chunk, dict) or not required_fields <= set(chunk):
                raise ValueError(f"chunks.json chunk {number} is missing required retrieval fields.")

        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        embedding = manifest.get("embedding") if isinstance(manifest, dict) else None
        if not isinstance(embedding, dict) or embedding.get("status") != "created":
            raise ValueError("The index manifest has no created embeddings. Re-run ingestion without --skip-embeddings.")
        model_name = embedding.get("model")
        if not isinstance(model_name, str) or not model_name:
            raise ValueError("The index manifest does not record an embedding model.")
        if manifest.get("chunkCount") != len(chunks):
            raise ValueError("The index manifest chunk count does not match chunks.json.")

        vectors = np.load(vectors_path, allow_pickle=False)
        index = cls(chunks, vectors, model_name=model_name, embedder=embedder)
        dimensions = embedding.get("dimensions")
        if dimensions is not None and dimensions != index.dimensions:
            raise ValueError("The index manifest embedding dimensions do not match embeddings.npy.")
        return index

    @property
    def dimensions(self) -> int:
        return int(self._embeddings.shape[1])

    def articles(self) -> list[ArticleReference]:
        """Return each indexed article once, independently of semantic retrieval."""

        unique: dict[str, ArticleReference] = {}
        for chunk in self._chunks:
            slug = str(chunk["articleSlug"])
            url = str(chunk["articleUrl"]).split("#", maxsplit=1)[0]
            unique.setdefault(
                slug,
                ArticleReference(title=str(chunk["articleTitle"]), slug=slug, url=url),
            )
        return sorted(unique.values(), key=lambda article: article.title.casefold())

    def article_costs(self) -> list[ArticleCostReference]:
        """Return compact structured cost/model metadata for every indexed article."""

        costs: dict[str, ArticleCostReference] = {}
        for chunk in self._chunks:
            if chunk.get("chunkType") != "generation-cost":
                continue
            slug = str(chunk["articleSlug"])
            raw_total = chunk.get("totalCostUsd")
            total = float(raw_total) if isinstance(raw_total, (int, float)) else None
            raw_models = chunk.get("models", [])
            models = tuple(str(model) for model in raw_models) if isinstance(raw_models, list) else ()
            raw_stages = chunk.get("stageSummaries", [])
            stages = tuple(stage for stage in raw_stages if isinstance(stage, dict)) if isinstance(raw_stages, list) else ()
            costs.setdefault(
                slug,
                ArticleCostReference(
                    title=str(chunk["articleTitle"]),
                    slug=slug,
                    url=str(chunk["articleUrl"]),
                    total_cost_usd=total,
                    cost_status=str(chunk["costStatus"]) if chunk.get("costStatus") is not None else None,
                    models=models,
                    stages=stages,
                ),
            )
        for article in self.articles():
            costs.setdefault(
                article.slug,
                ArticleCostReference(
                    title=article.title,
                    slug=article.slug,
                    url=f"{article.url}#ai-production-cost",
                    total_cost_usd=None,
                    cost_status=None,
                    models=(),
                    stages=(),
                ),
            )
        return sorted(costs.values(), key=lambda article: article.title.casefold())

    @staticmethod
    def _normalise(vectors: np.ndarray) -> np.ndarray:
        norms = np.linalg.norm(vectors, axis=1, keepdims=True)
        if np.any(norms == 0):
            raise ValueError("The retrieval index contains a zero-length embedding.")
        return vectors / norms

    def _get_embedder(self) -> QueryEmbedder:
        if self._embedder is None:
            self._embedder = OpenRouterEmbeddingClient(self.model_name)
        elif self._embedder.model != self.model_name:
            raise ValueError(
                f"Query embedding model '{self._embedder.model}' does not match index model '{self.model_name}'."
            )
        return self._embedder

    async def search(
        self,
        question: str,
        *,
        limit: int = 3,
        chunk_type: str | None = None,
    ) -> list[RetrievedChunk]:
        """Return the highest-scoring chunks for a non-empty English question."""

        question = question.strip()
        if not question:
            raise ValueError("A question is required.")
        if limit < 1:
            raise ValueError("Retrieval limit must be at least 1.")

        query_vector = np.asarray(await self._get_embedder().embed_query(question), dtype=np.float32)
        if query_vector.shape != (self.dimensions,):
            raise ValueError(
                f"Query embedding shape {query_vector.shape} does not match index dimensions {self.dimensions}."
            )
        query_vector = self._normalise(query_vector.reshape(1, -1))[0]
        scores = self._embeddings @ query_vector
        candidates = np.array(
            [
                index
                for index, chunk in enumerate(self._chunks)
                if chunk_type is None or chunk.get("chunkType", "lesson") == chunk_type
            ],
            dtype=int,
        )
        if not len(candidates):
            return []
        normalised_question = " ".join(re.findall(r"[a-z0-9]+", question.lower()))
        title_matches = np.array(
            [
                index
                for index in candidates
                if " ".join(re.findall(r"[a-z0-9]+", str(self._chunks[index]["articleTitle"]).lower()))
                in normalised_question
            ],
            dtype=int,
        )
        matched_indices = set(title_matches.tolist())
        if len(title_matches):
            candidates = title_matches
        ranked_candidates = candidates[np.argsort(-scores[candidates], kind="stable")]
        selected = ranked_candidates[: min(limit, len(ranked_candidates))]
        return [
            RetrievedChunk(
                id=str(self._chunks[index]["id"]),
                article_slug=str(self._chunks[index]["articleSlug"]),
                article_title=str(self._chunks[index]["articleTitle"]),
                article_url=str(self._chunks[index]["articleUrl"]),
                heading=str(self._chunks[index]["heading"]),
                text=str(self._chunks[index]["text"]),
                score=float(scores[index]),
                metadata_matched=int(index) in matched_indices,
            )
            for index in selected
        ]

    async def close(self) -> None:
        if self._embedder is not None:
            await self._embedder.aclose()
